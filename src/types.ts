export type Role = 'manager' | 'technician';

export interface User {
  id: string;
  username: string;
  password?: string;
  fullName: string;
  role: Role;
  department: string;
  isActive: boolean;
  updatedAt: number;
}

export type AssetCategory =
  | 'Intake & Screening'
  | 'Coagulation & Flocculation'
  | 'Clarification & Sedimentation'
  | 'Filtration (Sand & Carbon)'
  | 'Membrane Separation (RO)'
  | 'Chemical Dosing & Chlorination'
  | 'Pumps & Blowers'
  | 'Sludge Dewatering'
  | 'Instrumentation & SCADA';

export type AssetStatus = 'operational' | 'degraded' | 'under_maintenance' | 'offline';

export interface Asset {
  id: string;
  name: string;
  code: string; // e.g. P-101, RO-SKID-2
  parentId: string | null; // For hierarchical tree
  category: AssetCategory;
  status: AssetStatus;
  serialNumber: string;
  model: string;
  manufacturer: string;
  location: string;
  capacitySpecs: string; // e.g. "350 m³/h @ 4.2 bar"
  installDate: string; // ISO format YYYY-MM-DD
  operatingHours: number;
  imageUrl?: string;
  notes?: string;
  updatedAt: number;
  isDeleted?: boolean;
}

export interface SubAsset {
  id: string;
  assetId: string;
  name: string;
  partNumber: string;
  serialNumber: string;
  status: 'normal' | 'worn' | 'needs_replacement';
  notes?: string;
  updatedAt: number;
  isDeleted?: boolean;
}

export type MaintenanceType = 'preventive' | 'corrective' | 'emergency';

export type MaintenanceStatus =
  | 'scheduled'
  | 'in_progress'
  | 'pending_approval' // Technician submitted completion request
  | 'completed'        // Manager approved
  | 'rejected';        // Manager requested revisions

export interface UsedPart {
  storagePartId: string;
  partName: string;
  partNumber: string;
  quantityUsed: number;
  unitCost: number;
}

export interface MaintenanceEvent {
  id: string;
  assetId: string;
  assetName: string;
  assetCode: string;
  title: string;
  type: MaintenanceType;
  status: MaintenanceStatus;
  date: string; // ISO date
  deadlineDate?: string;
  hasDeadline?: boolean;
  affectedScheduleId?: string; // Reset this schedule upon completion
  isAutomatedPM?: boolean; // Generated by recurring schedule
  technicianId: string;
  technicianName: string;
  durationHours: number;
  description: string;
  solution?: string;
  partsUsed: UsedPart[];
  downtimeHours: number;
  approvedBy?: string;
  approvalNotes?: string;
  approvalDate?: string;
  updatedAt: number;
  isDeleted?: boolean;
}

export type IntervalType = 'days' | 'weeks' | 'months' | 'hours';

export interface MaintenanceSchedule {
  id: string;
  assetId: string;
  assetName: string;
  assetCode: string;
  taskTitle: string;
  description: string;
  intervalType: IntervalType;
  intervalValue: number;
  lastPerformedDate: string;
  nextDueDate: string;
  dueOperatingHours?: number;
  status: 'active' | 'paused' | 'overdue';
  assignedRole: Role;
  updatedAt: number;
  isDeleted?: boolean;
}

export interface StoragePart {
  id: string;
  partName: string;
  partNumber: string;
  category: string;
  quantityInStock: number;
  unit: string; // e.g. 'pcs', 'liters', 'sets', 'meters'
  minThreshold: number;
  unitCost: number; // in USD or local currency
  shelfLocation: string; // e.g. 'Warehouse-A / Shelf-2B'
  supplier?: string;
  compatibleAssets?: string[]; // Asset codes
  updatedAt: number;
  isDeleted?: boolean;
}

export type SyncStatus = 'synced' | 'syncing' | 'offline' | 'error' | 'pending';

export interface SyncMutation {
  id: string;
  timestamp: number;
  entityType: 'users' | 'assets' | 'subassets' | 'events' | 'schedules' | 'inventory';
  action: 'create' | 'update' | 'delete';
  entityId: string;
  data: Record<string, unknown>;
}

export type Language = 'en' | 'fa';
export type CalendarType = 'gregorian' | 'persian';
